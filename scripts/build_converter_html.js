/**
 * Membangun scripts/converter_bundle.js dan converter.html (MV3 CSP-safe + file://-safe)
 * dari sumber tunggal: scripts/docx_parser.js, scripts/afresto_next_exporter.js, scripts/gemini.js.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

function wrapAsBrowserModule(sourceCode, exposedSymbols) {
  const cleaned = sourceCode
    .replace(/^import\s+.*?;\r?\n/gm, '')
    .replace(/^export\s+(?=(?:async\s+)?function|const|let|var|class)/gm, '');
  const exportsAssign = exposedSymbols
    .map(sym => `  global.AfrestoBridge.${sym} = ${sym};`)
    .join('\n');
  return `(function (global) {\n  global.AfrestoBridge = global.AfrestoBridge || {};\n${cleaned}\n${exportsAssign}\n})(window);`;
}

export function buildStandaloneConverterAssets() {
  const templatePath = path.join(__dirname, 'converter.template.html');
  const parserPath = path.join(__dirname, 'docx_parser.js');
  const exporterPath = path.join(__dirname, 'afresto_next_exporter.js');
  const geminiPath = path.join(__dirname, 'gemini.js');

  const parserSrc = wrapAsBrowserModule(fs.readFileSync(parserPath, 'utf8'), ['parseDocx', 'parseQuestionsDirectly']);
  const exporterSrc = wrapAsBrowserModule(fs.readFileSync(exporterPath, 'utf8'), ['buildAfrestoNextDocx']);
  const geminiSrc = wrapAsBrowserModule(fs.readFileSync(geminiPath, 'utf8'), ['GeminiService', 'ALLOWED_MODELS']);

  const bundleContent = `/**\n * Copyright (c) 2026 Maulana Ibrahim\n * Built by : Maulana Ibrahim\n */\n// AUTO-GENERATED BY scripts/build_converter_html.js — JANGAN EDIT MANUAL\n${parserSrc}\n\n${exporterSrc}\n\n${geminiSrc}\n`;
  const bundleOut = path.join(__dirname, 'converter_bundle.js');
  fs.writeFileSync(bundleOut, bundleContent, 'utf8');

  // Versi eksternal bebas inline-script (100% lulus CSP Manifest V3 DAN jalan lewat file://)
  const template = fs.readFileSync(templatePath, 'utf8');
  const markerIdx = template.indexOf('<!-- AFRESTO_CORE_BUNDLE -->');
  if (markerIdx === -1) {
    throw new Error('Marker <!-- AFRESTO_CORE_BUNDLE --> tidak ditemukan di converter.template.html');
  }
  const bodyEndIdx = template.lastIndexOf('</body>');
  const converterHtml =
    template.slice(0, markerIdx) +
    '<script src="scripts/converter_bundle.js"></script>\n  <script src="scripts/converter_app.js"></script>\n' +
    template.slice(bodyEndIdx);

  fs.writeFileSync(path.join(rootDir, 'converter.html'), converterHtml, 'utf8');

  const distDir = path.join(rootDir, 'dist');
  if (fs.existsSync(distDir)) {
    fs.writeFileSync(path.join(distDir, 'converter.html'), converterHtml, 'utf8');
    fs.writeFileSync(path.join(distDir, 'scripts', 'converter_bundle.js'), bundleContent, 'utf8');
    fs.copyFileSync(path.join(__dirname, 'converter_app.js'), path.join(distDir, 'scripts', 'converter_app.js'));
  }

  console.log(`Berhasil membangun converter.html (${converterHtml.length} bytes) & converter_bundle.js (${bundleContent.length} bytes)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  buildStandaloneConverterAssets();
}
